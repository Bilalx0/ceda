import type { CedaAuditResult, CedaIssue, SeverityLevel } from '../types/ceda.js';

const SEVERITY_ORDER: Record<SeverityLevel, number> = {
  CRITICAL: 0,
  HIGH: 1,
  MEDIUM: 2,
  LOW: 3,
};

const SEVERITY_LABELS: Record<SeverityLevel, string> = {
  CRITICAL: 'CRITICAL',
  HIGH: 'HIGH',
  MEDIUM: 'MEDIUM',
  LOW: 'LOW',
};

function getRiskBadge(risk: CedaAuditResult['overallRisk']): string {
  switch (risk) {
    case 'PASS':
      return '**PASS**';
    case 'WARNING':
      return '**WARNING**';
    case 'BLOCK':
      return '**BLOCK**';
  }
}

function formatIssue(issue: CedaIssue): string {
  const location = issue.line ? `${issue.file}:${issue.line}` : issue.file;
  const fix = issue.suggestedFix ? `\n   - **Fix**: ${issue.suggestedFix}` : '';

  return `### ${issue.title}
- **Location**: \`${location}\`
- **Severity**: ${SEVERITY_LABELS[issue.severity]}
- **Type**: ${issue.type}
- **Description**: ${issue.description}${fix}
`;
}

function groupIssuesByType(issues: CedaIssue[]): Map<string, CedaIssue[]> {
  const grouped = new Map<string, CedaIssue[]>();

  for (const issue of issues) {
    const existing = grouped.get(issue.type) || [];
    existing.push(issue);
    grouped.set(issue.type, existing);
  }

  return grouped;
}

function sortIssuesBySeverity(issues: CedaIssue[]): CedaIssue[] {
  return [...issues].sort((a, b) => {
    return SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity];
  });
}

export function buildComment(auditResult: CedaAuditResult): string {
  const lines: string[] = [];

  lines.push('## CEDA Audit Report');
  lines.push('');
  lines.push(`**Overall Risk**: ${getRiskBadge(auditResult.overallRisk)}`);
  lines.push(`**Risk Score**: ${auditResult.riskScore}/100`);
  lines.push(`**Summary**: ${auditResult.summary}`);
  lines.push('');

  if (auditResult.testFileModified) {
    lines.push(
      '> **Note**: This PR modifies both source code and test files. Please verify test integrity manually.'
    );
    lines.push('');
  }

  if (auditResult.issues.length === 0) {
    lines.push('**No issues detected.** Code appears safe.');
  } else {
    const grouped = groupIssuesByType(auditResult.issues);

    for (const [type, issues] of grouped.entries()) {
      const sortedIssues = sortIssuesBySeverity(issues);

      lines.push(`### ${type} Issues (${issues.length})`);
      lines.push('');

      for (const issue of sortedIssues) {
        lines.push(formatIssue(issue));
      }
    }
  }

  lines.push('---');
  lines.push(
    '*Generated by [CEDA](https://github.com/your-username/ceda-auditor) - AI Code Debt Auditor*'
  );

  return lines.join('\n');
}

export function shouldPostComment(auditResult: CedaAuditResult, riskThreshold: number): boolean {
  if (auditResult.overallRisk === 'BLOCK') {
    return true;
  }

  if (auditResult.riskScore >= riskThreshold) {
    return true;
  }

  if (
    auditResult.issues.some((issue) => issue.severity === 'CRITICAL' || issue.severity === 'HIGH')
  ) {
    return true;
  }

  return false;
}
